#!/usr/bin/env python3
"""Runtime token and cost report from Prometheus (``make token-report``).

Queries the fcrm_* agent metrics the agent-worker (H2) exports through the
otel-collector and writes ``ops/token-analysis/runtime/<date>.md`` plus
``ops/token-analysis/runtime/latest.md``: tokens per agent and model, cost
per agent and per case, p95 latency per agent, and the busiest case's share
of the 120k-token cap. With no data yet (no agent has run) it still writes
the report, saying so, rather than failing.

Usage::

    python ops/scripts/token_report.py [--prometheus URL] [--range 24h]
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

logger = logging.getLogger("token_report")

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "ops" / "token-analysis" / "runtime"
CASE_CAP_TOKENS = 120_000

Row = tuple[dict[str, str], float]


def query(prometheus: str, promql: str) -> list[Row]:
    """Run an instant PromQL query; return ``(labels, value)`` rows."""
    url = f"{prometheus}/api/v1/query?" + urllib.parse.urlencode({"query": promql})
    with urllib.request.urlopen(url, timeout=10) as response:  # noqa: S310 - operator-supplied URL
        body = json.load(response)
    if body.get("status") != "success":
        raise RuntimeError(f"query failed: {promql}: {body}")
    return [(r["metric"], float(r["value"][1])) for r in body["data"]["result"]]


def table(rows: list[Row], keys: list[str], value: str, fmt: str) -> str:
    """Render rows as a Markdown table sorted by value, largest first."""
    if not rows:
        return "_no data in range_\n"
    head = "| " + " | ".join([*keys, value]) + " |\n"
    rule = "|" + "---|" * (len(keys) + 1) + "\n"
    body = "".join(
        "| " + " | ".join([labels.get(k, "") for k in keys] + [format(v, fmt)]) + " |\n"
        for labels, v in sorted(rows, key=lambda r: r[1], reverse=True)
    )
    return head + rule + body


def build(prometheus: str, window: str) -> str:
    """Query Prometheus and assemble the Markdown report."""
    tokens = query(
        prometheus,
        f"sum by (agent, model) (increase(fcrm_agent_tokens_total[{window}]))",
    )
    cost_agent = query(
        prometheus, f"sum by (agent) (increase(fcrm_agent_cost_usd_total[{window}]))"
    )
    cost_case = query(
        prometheus, f"sum by (case_id) (increase(fcrm_agent_cost_usd_total[{window}]))"
    )
    tokens_case = query(
        prometheus, f"sum by (case_id) (increase(fcrm_agent_tokens_total[{window}]))"
    )
    p95 = query(
        prometheus,
        "histogram_quantile(0.95, sum by (le, agent) "
        f"(rate(fcrm_agent_latency_ms_bucket[{window}])))",
    )
    total_tokens = sum(v for _, v in tokens)
    total_cost = sum(v for _, v in cost_agent)
    busiest = max(tokens_case, key=lambda r: r[1], default=None)
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# Runtime token report · {now}",
        "",
        f"Source: Prometheus `{prometheus}`, window `{window}`. Generated by "
        "`make token-report` (ops/scripts/token_report.py).",
        "",
        f"- Total tokens: **{total_tokens:,.0f}**",
        f"- Total cost: **${total_cost:,.4f}**",
        f"- Cases with spend: **{len(cost_case)}**",
    ]
    if busiest is not None:
        share = busiest[1] / CASE_CAP_TOKENS
        lines.append(
            f"- Busiest case: **{busiest[0].get('case_id', '?')}** at "
            f"{busiest[1]:,.0f} tokens ({share:.0%} of the {CASE_CAP_TOKENS:,} cap)"
        )
    if not tokens:
        lines += ["", "_No agent has reported tokens in this window yet._"]
    lines += [
        "",
        "## Tokens by agent and model",
        "",
        table(tokens, ["agent", "model"], "tokens", ",.0f"),
        "## Cost by agent (USD)",
        "",
        table(cost_agent, ["agent"], "usd", ",.4f"),
        "## Cost by case (USD)",
        "",
        table(cost_case, ["case_id"], "usd", ",.4f"),
        "## Agent latency p95 (ms)",
        "",
        table(p95, ["agent"], "p95_ms", ",.0f"),
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the dated report and refresh latest.md."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--prometheus", default="http://127.0.0.1:9090")
    parser.add_argument("--range", dest="window", default="24h")
    args = parser.parse_args(argv)
    try:
        report = build(args.prometheus.rstrip("/"), args.window)
    except (urllib.error.URLError, OSError, RuntimeError) as exc:
        logger.error(
            "cannot query Prometheus at %s: %s (is `make up-infra` running?)",
            args.prometheus,
            exc,
        )
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    dated = OUT_DIR / f"{datetime.now(UTC):%Y-%m-%d}.md"
    for path in (dated, OUT_DIR / "latest.md"):
        path.write_text(report + "\n", encoding="utf-8")
    logger.info("wrote %s and latest.md", dated.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
