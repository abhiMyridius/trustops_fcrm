#!/usr/bin/env python3
"""``make economy-profile``: a copy of ``ai/`` whose tiers use no Sonnet or Opus.

A live check of the whole system (``make demo``, ``make e2e``, the resilience
drills, ``make evals``) runs every tier on Bedrock, and Sonnet and Opus are the
expensive part. This builds ``.economy/``: a copy of ``ai/`` with only
``models/tiers.yaml`` changed, and a compose override that mounts the copy over
``/app/ai`` in ``api`` and ``harness``. The shipped ``ai/`` is never touched.

The chains are derived from the shipped file, so no model id is written here
(ADR-04):

* ``mid`` and ``strong`` take the ``cheap`` tier's chain (Haiku, then Nova Lite);
* ``judge`` (the critic, the eval judges) runs on Nova Pro with the ``cheap``
  primary as its fallback, so the critic still differs from the assessor it
  checks and a Nova answer the contract refuses retries on Haiku (ADR-14).

Budgets, output caps, prices and every other key are kept, so a run's cost is
still read at the verified prices. The profile checks the vendor's models, not
the shipped chains: a result from it is never a baseline and says so.

Usage::

    python ops/scripts/economy_profile.py            # writes .economy/
    python ops/scripts/economy_profile.py --out DIR  # somewhere else

Exit code 0 on success, 1 when the shipped tiers cannot be reduced or the output
folder is not one this script made.
"""

from __future__ import annotations

import argparse
import copy
import logging
import shutil
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, Final, Optional

import yaml

logger = logging.getLogger("economy_profile")

REPO_ROOT: Final = Path(__file__).resolve().parents[2]
SOURCE_AI: Final = REPO_ROOT / "ai"
DEFAULT_OUT: Final = REPO_ROOT / ".economy"
TIERS_RELATIVE: Final = Path("models") / "tiers.yaml"
OVERRIDE_NAME: Final = "compose.override.yaml"
MARKER_NAME: Final = ".economy-profile"
CONTAINER_AI_ROOT: Final = "/app/ai"
COMPOSE_SERVICES: Final = ("api", "harness")
#: Tiers that take the ``cheap`` chain.
FOLLOW_CHEAP: Final = ("mid", "strong")
JUDGE_TIER: Final = "judge"
JUDGE_LABEL: Final = "Nova Pro"
#: Label prefixes no economy chain may contain.
EXPENSIVE_LABELS: Final = ("Sonnet", "Opus")
HEADER: Final = (
    "# GENERATED by ops/scripts/economy_profile.py. The economy profile: no\n"
    "# Sonnet or Opus in any tier chain. Not the shipped configuration; a result\n"
    "# produced with it is never an eval baseline. Do not edit or commit.\n"
)


class EconomyProfileError(RuntimeError):
    """The shipped tiers cannot be reduced, or the output folder is not ours."""


def model_label(config: Mapping[str, Any], model_id: str) -> str:
    """The ``label`` ``models`` gives ``model_id``.

    Args:
        config: A parsed ``tiers.yaml``.
        model_id: A model id used in a tier chain.

    Returns:
        The model's label, for example ``Haiku 4.5``.

    Raises:
        EconomyProfileError: ``models`` has no labelled entry for the id.
    """
    entry = (config.get("models") or {}).get(model_id)
    if not isinstance(entry, Mapping) or "label" not in entry:
        msg = f"tiers.yaml models has no label for {model_id!r}"
        raise EconomyProfileError(msg)
    return str(entry["label"])


def find_model(config: Mapping[str, Any], label: str) -> str:
    """The id of the model labelled ``label``.

    Raises:
        EconomyProfileError: No model has that label.
    """
    for model_id, entry in (config.get("models") or {}).items():
        if isinstance(entry, Mapping) and entry.get("label") == label:
            return str(model_id)
    msg = f"tiers.yaml models has no model labelled {label!r}"
    raise EconomyProfileError(msg)


def tier_of(config: Mapping[str, Any], name: str) -> dict[str, Any]:
    """The mutable ``tiers.<name>`` mapping.

    Raises:
        EconomyProfileError: The tier is not configured.
    """
    tier = (config.get("tiers") or {}).get(name)
    if not isinstance(tier, dict) or "primary" not in tier:
        msg = f"tiers.yaml has no usable {name!r} tier"
        raise EconomyProfileError(msg)
    return tier


def chain_of(tier: Mapping[str, Any]) -> list[str]:
    """A tier's model ids in call order: the primary, then its fallbacks."""
    return [str(tier["primary"]), *map(str, tier.get("fallbacks") or [])]


def expensive_models(config: Mapping[str, Any]) -> list[str]:
    """Every ``<tier>: <label>`` whose chain holds a Sonnet or an Opus."""
    found: list[str] = []
    for name in config.get("tiers") or {}:
        for model_id in chain_of(tier_of(config, name)):
            label = model_label(config, model_id)
            if label.startswith(EXPENSIVE_LABELS):
                found.append(f"{name}: {label}")
    return found


def build_economy_config(shipped: Mapping[str, Any]) -> dict[str, Any]:
    """The shipped ``tiers.yaml`` with every tier chain made cheap.

    Args:
        shipped: The parsed ``ai/models/tiers.yaml``. It is not modified.

    Returns:
        A new mapping equal to ``shipped`` except for the ``mid``, ``strong``
        and ``judge`` chains.

    Raises:
        EconomyProfileError: A tier or the judge's model is missing, or a
            Sonnet or an Opus is still in a chain.
    """
    economy = copy.deepcopy(dict(shipped))
    cheap = tier_of(economy, "cheap")
    cheap_primary = str(cheap["primary"])
    cheap_fallbacks = [str(model) for model in cheap.get("fallbacks") or []]
    for name in FOLLOW_CHEAP:
        tier = tier_of(economy, name)
        tier["primary"] = cheap_primary
        tier["fallbacks"] = list(cheap_fallbacks)
    judge = tier_of(economy, JUDGE_TIER)
    judge["primary"] = find_model(economy, JUDGE_LABEL)
    judge["fallbacks"] = [cheap_primary]
    remaining = expensive_models(economy)
    if remaining:
        msg = f"the economy profile still holds {', '.join(remaining)}"
        raise EconomyProfileError(msg)
    return economy


def render_tiers(economy: Mapping[str, Any]) -> str:
    """``tiers.yaml`` text for ``economy``, with the generated-file header."""
    body = yaml.safe_dump(dict(economy), sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def render_compose_override(ai_dir: Path) -> str:
    """A compose override that mounts ``ai_dir`` over ``/app/ai``.

    Compose merges a service's ``volumes`` by mount path, so this replaces only
    the ``ai`` mount of each service and keeps its other volumes.
    """
    services = {
        name: {"volumes": [f"{ai_dir}:{CONTAINER_AI_ROOT}:ro"]}
        for name in COMPOSE_SERVICES
    }
    return HEADER + yaml.safe_dump({"services": services}, sort_keys=False)


def prepare_out_dir(out_dir: Path) -> None:
    """Empty ``out_dir`` if an earlier run of this script made it.

    Raises:
        EconomyProfileError: ``out_dir`` exists and is not ours (no marker), so
            nothing in it is deleted.
    """
    if out_dir.exists():
        if not (out_dir / MARKER_NAME).is_file():
            msg = f"{out_dir} exists and was not made by this script; not deleting it"
            raise EconomyProfileError(msg)
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    (out_dir / MARKER_NAME).write_text(
        "made by ops/scripts/economy_profile.py\n", encoding="utf-8"
    )


def write_profile(source_ai: Path, out_dir: Path) -> Path:
    """Write the economy ``ai/`` copy and the compose override.

    Args:
        source_ai: The shipped ``ai/`` folder.
        out_dir: The folder to fill; see :func:`prepare_out_dir`.

    Returns:
        The path of the compose override.

    Raises:
        EconomyProfileError: See :func:`prepare_out_dir` and
            :func:`build_economy_config`.
        OSError: A file could not be read or written.
    """
    tiers_path = source_ai / TIERS_RELATIVE
    shipped = yaml.safe_load(tiers_path.read_text(encoding="utf-8"))
    economy = build_economy_config(shipped)
    prepare_out_dir(out_dir)
    ai_dir = out_dir / "ai"
    shutil.copytree(
        source_ai, ai_dir, ignore=shutil.ignore_patterns("__pycache__", "*.pyc")
    )
    (ai_dir / TIERS_RELATIVE).write_text(render_tiers(economy), encoding="utf-8")
    override = out_dir / OVERRIDE_NAME
    override.write_text(render_compose_override(ai_dir.resolve()), encoding="utf-8")
    return override


def describe(economy: Mapping[str, Any]) -> list[str]:
    """One line per tier: its chain by label."""
    return [
        f"  {name:<7}"
        + " -> ".join(model_label(economy, m) for m in chain_of(tier_of(economy, name)))
        for name in economy["tiers"]
    ]


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=SOURCE_AI, help="the ai/ root")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output folder")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    try:
        override = write_profile(args.source, args.out)
        economy = yaml.safe_load(
            (args.out / "ai" / TIERS_RELATIVE).read_text(encoding="utf-8")
        )
    except (EconomyProfileError, OSError, yaml.YAMLError) as exc:
        logger.error("economy profile not written: %s", exc)
        return 1
    logger.info("economy profile written to %s; tier chains:", args.out)
    for line in describe(economy):
        logger.info(line)
    logger.info("compose override: %s", override)
    return 0


if __name__ == "__main__":
    sys.exit(main())
