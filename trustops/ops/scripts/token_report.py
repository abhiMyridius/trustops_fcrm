#!/usr/bin/env python3
"""Runtime token and cost report from OpenObserve (``make token-report``).

Queries the fcrm_* agent metrics the agent-worker (H2) exports through the
otel-collector into OpenObserve (ADR-72), over its Prometheus-compatible API,
and writes ``ops/token-analysis/runtime/<date>.md`` plus
``ops/token-analysis/runtime/latest.md``: tokens per agent and model and per
direction, cost per agent, p95 latency per agent and the highest per-attempt
budget use. With no data yet (no agent has run) it still writes the report,
saying so, rather than failing.

There is no per-case table: metric labels carry no ``case_id`` (an unbounded
label would make one series per case). A case's own tokens and cost are in
its audit trail's token records and the harness monitor.

Usage::

    python ops/scripts/token_report.py [--env-file .env] [--url URL] [--range 24h]
"""

from __future__ import annotations

import argparse
import logging
import sys
from datetime import UTC, datetime
from pathlib import Path

from openobserve_client import OpenObserve, OpenObserveError, Row

logger = logging.getLogger("token_report")

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "ops" / "token-analysis" / "runtime"


def price_footnote() -> str:
    """What the cost lines say about their prices (``ai/models/tiers.yaml``).

    Needs the evals package, so it answers only under ``uv run`` (``make
    token-report`` does); elsewhere it says it could not read the status.
    """
    try:
        from fcrm_agents.models import load_tiers_config
        from fcrm_evals.instructions import DEFAULT_AI_ROOT
        from fcrm_evals.usage import PriceTable
    except ImportError:
        return (
            "price status not read (run it through `uv run --project src/backend "
            "--all-packages python ops/scripts/token_report.py`)"
        )
    return PriceTable.from_tiers(load_tiers_config(DEFAULT_AI_ROOT)).note()


def table(rows: list[Row], keys: list[str], value: str, fmt: str) -> str:
    """Render rows as a Markdown table sorted by value, largest first."""
    if not rows:
        return "_no data in range_\n"
    head = "| " + " | ".join([*keys, value]) + " |\n"
    rule = "|" + "---|" * (len(keys) + 1) + "\n"
    body = "".join(
        "| " + " | ".join([labels.get(k, "") for k in keys] + [format(v, fmt)]) + " |\n"
        for labels, v in sorted(rows, key=lambda r: r[1], reverse=True)
    )
    return head + rule + body


def build(client: OpenObserve, window: str) -> str:
    """Query OpenObserve and assemble the Markdown report."""
    tokens = client.query(
        f"sum by (agent, model) (increase(fcrm_agent_tokens_total[{window}]))"
    )
    directions = client.query(
        f"sum by (direction) (increase(fcrm_agent_tokens_total[{window}]))"
    )
    cost_agent = client.query(
        f"sum by (agent) (increase(fcrm_agent_cost_usd_total[{window}]))"
    )
    p95 = client.query(
        "histogram_quantile(0.95, sum by (le, agent) "
        f"(rate(fcrm_agent_latency_ms_bucket[{window}])))"
    )
    budget = client.query("max by (agent) (fcrm_budget_used_ratio)")
    total_tokens = sum(v for _, v in tokens)
    total_cost = sum(v for _, v in cost_agent)
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# Runtime token report · {now}",
        "",
        f"Source: OpenObserve `{client.base}` (organisation `{client.org}`), "
        f"window `{window}`. Generated by `make token-report` "
        "(ops/scripts/token_report.py).",
        "",
        f"- Total tokens: **{total_tokens:,.0f}**",
        f"- Total cost: **${total_cost:,.4f}**",
        "- Cost is an estimate at the prices in `ai/models/tiers.yaml`: "
        f"{price_footnote()}",
        "- Per case: the metrics carry no `case_id` (ADR-72); a case's tokens "
        "and cost are in its audit token records and the harness monitor.",
    ]
    if not tokens:
        lines += ["", "_No agent has reported tokens in this window yet._"]
    lines += [
        "",
        "## Tokens by agent and model",
        "",
        table(tokens, ["agent", "model"], "tokens", ",.0f"),
        "## Tokens by direction",
        "",
        "`input` is the uncached part, so the four add up to the billed total.",
        "",
        table(directions, ["direction"], "tokens", ",.0f"),
        "## Cost by agent (USD)",
        "",
        table(cost_agent, ["agent"], "usd", ",.4f"),
        "## Agent latency p95 (ms)",
        "",
        table(p95, ["agent"], "p95_ms", ",.0f"),
        "## Budget use, last job (tokens / the tier's per-attempt budget)",
        "",
        table(budget, ["agent"], "ratio", ".2f"),
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the dated report and refresh latest.md."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env-file", type=Path, default=ROOT / ".env")
    parser.add_argument("--url", help="OpenObserve base URL (default: from .env)")
    parser.add_argument("--range", dest="window", default="24h")
    args = parser.parse_args(argv)
    try:
        client = OpenObserve.from_env(args.env_file, url=args.url)
        report = build(client, args.window)
    except OpenObserveError as exc:
        logger.error("token-report: %s", exc)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    dated = OUT_DIR / f"{datetime.now(UTC):%Y-%m-%d}.md"
    for path in (dated, OUT_DIR / "latest.md"):
        path.write_text(report + "\n", encoding="utf-8")
    logger.info("wrote %s and latest.md", dated.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
