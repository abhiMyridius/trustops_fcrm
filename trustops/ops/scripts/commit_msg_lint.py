#!/usr/bin/env python3
"""commit-msg hook: every commit traces to a decision and an SDLC stage.

Convention (CLAUDE.md): ``type(scope): summary [D-xx, ADR-nn]`` with
``Stage:`` and ``Gate:`` trailers. Enforced:

* the subject is ``type(scope): summary`` with a known type;
* the message references at least one decision (``D-<n>`` or ``ADR-<n>``);
* a ``Stage:`` trailer names one of the six SDLC stages.

A missing ``Gate:`` trailer is reported but does not block. Merge and
revert commits generated by git pass unchanged.
"""

from __future__ import annotations

import logging
import re
import sys
from pathlib import Path

logger = logging.getLogger("commit_msg_lint")

TYPES = (
    "feat|fix|docs|test|tests|chore|refactor|ops|perf|build|ci|style|revert|eval|evals"
)
SUBJECT = re.compile(rf"^({TYPES})(\([a-z0-9][a-z0-9._/-]*\))?!?: \S.*")
DECISION = re.compile(r"\b(D-\d+[a-z]?|ADR-\d+)\b")
STAGE = re.compile(
    r"^Stage:\s*(requirements|design|development|testing|deployment|operations)\b",
    re.IGNORECASE | re.MULTILINE,
)
GATE = re.compile(r"^Gate:\s*\S", re.MULTILINE)


def lint(message: str) -> list[str]:
    """Return the list of convention violations in a commit message."""
    body = "\n".join(
        ln for ln in message.splitlines() if not ln.startswith("#")
    ).strip()
    subject = body.splitlines()[0] if body else ""
    if subject.startswith(("Merge ", 'Revert "', "fixup! ", "squash! ")):
        return []
    problems = []
    if not SUBJECT.match(subject):
        problems.append(f"subject must be 'type(scope): summary' with type in {TYPES}")
    if not DECISION.search(body):
        problems.append("reference at least one decision: D-xx or ADR-nn")
    if not STAGE.search(body):
        stages = "requirements|design|development|testing|deployment|operations"
        problems.append(f"add a 'Stage: <{stages}>' trailer")
    return problems


def main(argv: list[str]) -> int:
    """Lint the message file git passes as the first argument."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if len(argv) < 2:
        logger.error("usage: commit_msg_lint.py <commit-msg-file>")
        return 2
    message = Path(argv[1]).read_text(encoding="utf-8")
    problems = lint(message)
    for problem in problems:
        logger.error("commit message: %s", problem)
    if not problems and not GATE.search(message):
        logger.warning("commit message: no 'Gate:' trailer (recommended)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
