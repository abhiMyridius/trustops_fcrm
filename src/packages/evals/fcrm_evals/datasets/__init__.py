"""The bundled datasets: one ``<agent>.jsonl`` per agent under ``data/``.

Like ``fcrm_seed``'s ``seed.json``, the files are package data generated by
code (:mod:`fcrm_evals.datasets.build`) and committed; ``build --check``
fails when a committed file differs from a fresh build.
"""

from __future__ import annotations

import hashlib
import logging
from importlib import resources
from pathlib import Path
from typing import Final

from fcrm_contracts.enums import AgentName

from fcrm_evals.rows import EvalRow

logger = logging.getLogger(__name__)

DATA_DIR: Final[Path] = Path(
    str(resources.files("fcrm_evals").joinpath("datasets", "data"))
)


def dataset_path(agent: AgentName) -> Path:
    """The bundled dataset file of ``agent``."""
    return DATA_DIR / f"{agent.value}.jsonl"


def dataset_name(agent: AgentName, n: int) -> str:
    """The dataset id reported in results: ``<agent>/<kind>-<rows>``."""
    kinds = {
        AgentName.SCREENING: "fast-lane",
        AgentName.INTAKE: "extraction",
        AgentName.RESEARCH: "clauses",
        AgentName.ASSESSMENT: "ratings",
        AgentName.CRITIC: "planted",
        AgentName.NARRATIVE: "recommendation",
        AgentName.EXAMINER: "questions",
        AgentName.WATCHLIST: "reflag",
        AgentName.POLICY_GAP: "suggestions",
    }
    return f"{agent.value}/{kinds[agent]}-{n}"


def load_rows(path: Path) -> list[EvalRow]:
    """Every row of a ``.jsonl`` dataset file, validated."""
    with path.open(encoding="utf-8") as handle:
        return [EvalRow.model_validate_json(line) for line in handle if line.strip()]


def load(agent: AgentName) -> list[EvalRow]:
    """The bundled dataset of ``agent``."""
    return load_rows(dataset_path(agent))


def file_sha256(path: Path) -> str:
    """Hex sha256 of a dataset file (recorded in every result)."""
    return hashlib.sha256(path.read_bytes()).hexdigest()
